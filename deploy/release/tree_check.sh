#!/usr/bin/env bash
# Сверка дерева перед меткой (design 004, развилка 004-18): дерево коммита main равно дереву последнего зелёного
# коммита ci/*. Метка сжигает номер версии, поэтому лишний коммит между последним прогоном CI и main ловится до push.
#   tree_check.sh <коммит метки> <ci-ref>   например: tree_check.sh main origin/ci/release-check
# Первый аргумент - тот коммит, который собираются пометить (чаще всего верхний main; sha тоже годится).
# Это страховка, не граница доверия: границу держит image-verify в ops-ВМ (004-8). Какой прогон ci/* зелёный —
# смотрит человек или рабочая ВМ (gh run list); скрипт сравнивает только деревья.
# Код 0 — деревья равны; 1 — различаются или ссылка не найдена.
set -euo pipefail

die() {
  echo "tree_check: $*" >&2
  exit 1
}

[ $# -eq 2 ] || die "использование: tree_check.sh <коммит метки> <ci-ref>"
for r in "$1" "$2"; do
  [[ $r =~ ^[A-Za-z0-9][A-Za-z0-9._/-]*$ ]] || die "имя ссылки «$r» не по формату"
done
a=$(git rev-parse --verify --quiet "$1^{tree}") || die "нет ссылки $1"
b=$(git rev-parse --verify --quiet "$2^{tree}") || die "нет ссылки $2"
[ "$a" = "$b" ] || die "дерево $1 ($a) ≠ дереву $2 ($b): между зелёным ci/* и помечаемым коммитом есть правки"
echo "tree_check: деревья равны ($a)"
